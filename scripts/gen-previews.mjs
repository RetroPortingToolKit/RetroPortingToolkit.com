// Regenerate src/generated/previews.ts from the clips actually present in
// public/previews/. A slug listed here gets an animated card (canvas-decoded
// MP4 with its .webp first frame as the poster) instead of a static cover.
// Run after adding or removing a clip:  node scripts/gen-previews.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DIR = path.join(ROOT, "public", "previews");
const OUT = path.join(ROOT, "src", "generated", "previews.ts");

// The hero reel is not a card preview.
const SKIP = new Set(["hero-montage"]);

const slugs = fs.existsSync(DIR)
  ? fs
      .readdirSync(DIR)
      .filter((f) => f.endsWith(".mp4"))
      .map((f) => f.slice(0, -4))
      .filter((s) => !SKIP.has(s))
      .filter((s) => fs.existsSync(path.join(DIR, `${s}.webp`)))
      .sort()
  : [];

const body =
  `// GENERATED by scripts/gen-previews.mjs. Do not edit by hand.\n` +
  `// Slugs with a short looping card preview at /previews/<slug>.mp4, whose\n` +
  `// first frame is mirrored at /previews/<slug>.webp for the still state.\n` +
  `export const PREVIEW_SLUGS: ReadonlySet<string> = new Set([\n` +
  slugs.map((s) => `  ${JSON.stringify(s)},`).join("\n") +
  (slugs.length ? "\n" : "") +
  `]);\n\n` +
  `export function previewFor(slug: string | undefined): { mp4: string; poster: string } | undefined {\n` +
  `  if (!slug || !PREVIEW_SLUGS.has(slug)) return undefined;\n` +
  `  return { mp4: \`/previews/\${slug}.mp4\`, poster: \`/previews/\${slug}.webp\` };\n` +
  `}\n`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, body);
console.log(`[previews] ${slugs.length} card clips -> src/generated/previews.ts`);
