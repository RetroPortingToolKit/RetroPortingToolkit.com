CREATE TABLE IF NOT EXISTS wiki_users (
  github_id TEXT PRIMARY KEY,
  login TEXT NOT NULL COLLATE NOCASE UNIQUE,
  discord_id TEXT UNIQUE,
  docs INTEGER NOT NULL DEFAULT 0,
  suspended INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS wiki_protections (path TEXT PRIMARY KEY);
CREATE TABLE IF NOT EXISTS wiki_links (hash TEXT PRIMARY KEY, github_id TEXT NOT NULL, expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS wiki_audit (id INTEGER PRIMARY KEY AUTOINCREMENT, actor TEXT NOT NULL, action TEXT NOT NULL, target TEXT NOT NULL, reason TEXT NOT NULL, at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS wiki_limits (identity TEXT PRIMARY KEY, window INTEGER NOT NULL, count INTEGER NOT NULL);
